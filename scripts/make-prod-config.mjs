#!/usr/bin/env node
/**
 * Builds shopify.app.production.toml from the dev config (shopify.app.toml), keeping the
 * production app's client_id and name, and pointing every URL at the production host.
 *
 * Usage (after `shopify app config link` created shopify.app.production.toml):
 *   node scripts/make-prod-config.mjs https://perks.tofoapp.com
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const url = (process.argv[2] || "https://perks.tofoapp.com").replace(/\/$/, "");
if (!/^https:\/\/[a-z0-9.-]+$/i.test(url)) {
  console.error(`Invalid URL: ${url}`);
  process.exit(1);
}
const prodPath = "shopify.app.production.toml";
if (!existsSync(prodPath)) {
  console.error(`${prodPath} not found. Run: shopify app config link  (create a new app, name the config "production")`);
  process.exit(1);
}

const prod = readFileSync(prodPath, "utf8");
const pick = (key) => (prod.match(new RegExp(`^${key}\\s*=\\s*"([^"]+)"`, "m")) || [])[1];
const clientId = pick("client_id");
const name = pick("name") || "Employee Perks";
if (!clientId) {
  console.error(`No client_id in ${prodPath}`);
  process.exit(1);
}

let out = readFileSync("shopify.app.toml", "utf8")
  .replace(/^client_id = ".*"$/m, `client_id = "${clientId}"`)
  .replace(/^name = ".*"$/m, `name = "${name}"`)
  .replace(/^application_url = ".*"$/m, `application_url = "${url}"`)
  .replace(/^url = "https:\/\/[^"]*\/proxy"$/m, `url = "${url}/proxy"`)
  .replace(/^redirect_urls = \[.*\]$/m, `redirect_urls = [ "${url}/api/auth" ]`)
  .replace(/^automatically_update_urls_on_dev = true$/m, "automatically_update_urls_on_dev = false");

out = `# PRODUCTION config, generated by scripts/make-prod-config.mjs. Re-run after changing shopify.app.toml.\n${out}`;
writeFileSync(prodPath, out);
console.log(`Wrote ${prodPath} (client_id ${clientId}, ${url})`);
